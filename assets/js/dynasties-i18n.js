  const STORE_KEY = 'dy-lang';
  const listeners = [];
  let current = 'en';

  function read() {
    try {
      const saved = localStorage.getItem(STORE_KEY);
      if (saved && STRINGS[saved]) return saved;
    } catch (e) {
      /* storage blocked */
    }
    return 'en';
  }

  function t(key, fallback, params) {
    let s = (STRINGS[current] && STRINGS[current][key]) || STRINGS.en[key] || fallback || key;
    if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
    return s;
  }

  function apply() {
    document.documentElement.lang = current;
    for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n, el.textContent);
    for (const el of document.querySelectorAll('[data-i18n-placeholder]')) {
      el.placeholder = t(el.dataset.i18nPlaceholder, el.placeholder);
    }
    for (const el of document.querySelectorAll('[data-i18n-aria]')) {
      el.setAttribute('aria-label', t(el.dataset.i18nAria, el.getAttribute('aria-label')));
    }
    for (const b of document.querySelectorAll('.dy-lang button')) {
      b.setAttribute('aria-pressed', String(b.dataset.lang === current));
    }
  }

  function set(lang) {
    if (!STRINGS[lang]) return;
    current = lang;
    try {
      localStorage.setItem(STORE_KEY, lang);
    } catch (e) {
      /* storage blocked */
    }
    apply();
    for (const fn of listeners) fn(lang);
  }

  window.DYI18N = { t, lang: () => current, set, onChange: (fn) => listeners.push(fn) };

  // Deferred scripts run after parsing, so the markup is ready.
  current = read();
  apply();
  for (const b of document.querySelectorAll('.dy-lang button')) b.addEventListener('click', () => set(b.dataset.lang));
